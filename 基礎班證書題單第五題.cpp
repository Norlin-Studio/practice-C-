#include<bits/stdc++.h>
using namespace std;
/*
觀察每筆輸出，length 只改變符號為 '|' 的長度，對於符號 '-'不影響

建立最基礎輸出格式，再用for迴圈處理 '|'的數量
注意到每個數字都會有 3 個放 '-' 的空間，這是固定項目
因為每次輸出是一橫列，所以我們每次都要處理一層
比如說 2, 12345 這個範例，我們要依序輸出 12345 各自的第一排，然後 12345 各自的第二排...

我們總共有 10 種數字 (0~9)，每種數字的最基本款有五層
所以創建一個 10*5 的二維陣列方便查找。
*/

string arr[10][5]={
	/*
	這裡是從 0,1,2...8,9 的基本結構，後續要加長就用這個表  
	每個數字五列，每列有三行  
	*/
	{{" - "},{"| |"},{"   "},{"| |"},{" - "}},
	{{"   "},{"  |"},{"   "},{"  |"},{"   "}},
	{{" - "},{"  |"},{" - "},{"|  "},{" - "}},
	{{" - "},{"  |"},{" - "},{"  |"},{" - "}},
	{{"   "},{"| |"},{" - "},{"  |"},{"   "}},
	{{" - "},{"|  "},{" - "},{"  |"},{" - "}},
	{{" - "},{"|  "},{" - "},{"| |"},{" - "}},
	{{" - "},{"  |"},{"   "},{"  |"},{"   "}},
	{{" - "},{"| |"},{" - "},{"| |"},{" - "}},
	{{" - "},{"| |"},{" - "},{"  |"},{" - "}}
	
};

int main() {
	int length;
	string s; // string比較好跑回圈 因為 string 有自己的索引值 
	while(cin >> length >> s) {
		if(length == 0 && s == "0") break;
		for(int level = 0; level < 5; level++) { //基礎款五層 
			
			if(level % 2 == 0) { // 偶數層 (只有一橫列的輸出)
				for(size_t i = 0; i < s.size(); i++) { // 處理每個數字
					// 只有中間要加長，最左跟右側不用  
					cout << arr[s[i]-'0'][level][0]; // 最左 
					for(int j = 0; j < length; j++) {
						cout << arr[s[i]-'0'][level][1]; // 橫向拓寬 
					}
					cout << arr[s[i]-'0'][level][2]; // 最右 
					cout << (i == s.size()-1 ? "\n" : " "); // 換行或是兩數字間的空格 
				}
			} else { // 基數層 有 length 個列的輸出 
				for(int k = 0; k < length; k++) { // 總共 length 列 
					for(size_t i = 0; i < s.size(); i++) {
						cout << arr[s[i]-'0'][level][0]; // 最左 
						for(int j = 0; j < length; j++) cout << arr[s[i]-'0'][level][1]; // 橫向拓寬 
						cout << arr[s[i]-'0'][level][2]; // 最右 
						cout << (i == s.size()-1 ? "\n" : " "); // 換行或是兩數字間的空格 
					} 
				}
			}
		}
		cout << "\n";
	}
}